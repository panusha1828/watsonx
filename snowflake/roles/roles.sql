-- ============================================================================
-- roles.sql
-- Role hierarchy and grants. See docs/data-governance.md for the access model.
-- ============================================================================

CREATE ROLE IF NOT EXISTS RETAIL360_ADMIN;
CREATE ROLE IF NOT EXISTS RETAIL360_TRANSFORMER;
CREATE ROLE IF NOT EXISTS RETAIL360_ANALYST;
CREATE ROLE IF NOT EXISTS RETAIL360_READER;

GRANT ROLE RETAIL360_TRANSFORMER TO ROLE RETAIL360_ADMIN;
GRANT ROLE RETAIL360_ANALYST TO ROLE RETAIL360_ADMIN;
GRANT ROLE RETAIL360_READER TO ROLE RETAIL360_ANALYST;

-- Database-level usage
GRANT USAGE ON DATABASE RETAIL360 TO ROLE RETAIL360_TRANSFORMER;
GRANT USAGE ON DATABASE RETAIL360 TO ROLE RETAIL360_ANALYST;
GRANT USAGE ON DATABASE RETAIL360 TO ROLE RETAIL360_READER;

-- RAW: read-only for transformer, no access for analyst/reader
GRANT USAGE ON SCHEMA RETAIL360.RAW TO ROLE RETAIL360_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA RETAIL360.RAW TO ROLE RETAIL360_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RETAIL360.RAW TO ROLE RETAIL360_TRANSFORMER;

-- STAGING / INTERMEDIATE: full DML for transformer only
GRANT ALL ON SCHEMA RETAIL360.STAGING TO ROLE RETAIL360_TRANSFORMER;
GRANT ALL ON SCHEMA RETAIL360.INTERMEDIATE TO ROLE RETAIL360_TRANSFORMER;

-- MARTS: write for transformer, read for analyst/reader
GRANT ALL ON SCHEMA RETAIL360.MARTS TO ROLE RETAIL360_TRANSFORMER;
GRANT USAGE ON SCHEMA RETAIL360.MARTS TO ROLE RETAIL360_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA RETAIL360.MARTS TO ROLE RETAIL360_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RETAIL360.MARTS TO ROLE RETAIL360_ANALYST;
GRANT USAGE ON SCHEMA RETAIL360.MARTS TO ROLE RETAIL360_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA RETAIL360.MARTS TO ROLE RETAIL360_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RETAIL360.MARTS TO ROLE RETAIL360_READER;

-- Warehouse grants
GRANT USAGE ON WAREHOUSE LOADING_WH TO ROLE RETAIL360_TRANSFORMER;
GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE RETAIL360_TRANSFORMER;
GRANT USAGE ON WAREHOUSE REPORTING_WH TO ROLE RETAIL360_ANALYST;
GRANT USAGE ON WAREHOUSE REPORTING_WH TO ROLE RETAIL360_READER;
